/// Returns the pixel (x, y) of `ch`'s glyph in the atlas, or `None` if not printable ASCII.
pub fn glyph_position(ch: char) -> Option<(u8, u8)> {
    let code = ch as usize;
    if (0x20..=0x7E).contains(&code) { Some(GLYPH_ATLAS_POSITIONS[code - 0x20]) } else { None }
}
