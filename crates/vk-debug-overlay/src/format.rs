use ash::vk;

#[derive(Copy, Clone, Debug, PartialEq, Eq)]
pub enum NumericFormat {
    Unorm,
    Snorm,
    Uscaled,
    Sscaled,
    Uint,
    Sint,
    Sfloat,
    Ufloat,
    Srgb,
    Bool,
    Sfixed5,
}

#[derive(Copy, Clone, Debug)]
pub struct ComponentInfo {
    pub name: &'static str,
    pub bits: u8,
    pub numeric_format: NumericFormat,
    pub plane_index: Option<u8>,
}

#[derive(Copy, Clone, Debug)]
pub struct PlaneInfo {
    pub width_divisor: u32,
    pub height_divisor: u32,
    pub compatible: vk::Format,
}

#[derive(Copy, Clone, Debug)]
pub struct FormatInfo {
    /// Size in bytes of one texel block.
    pub block_size: u32,
    /// Number of texels per texel block.
    pub texels_per_block: u32,
    /// Width/height/depth extent of one texel block. `[1, 1, 1]` for uncompressed formats.
    pub block_extent: [u32; 3],
    /// Bit width of the packed representation, if applicable.
    pub packed: Option<u32>,
    /// Chroma subsampling for YCbCr formats (420, 422, or 444).
    pub chroma: Option<u32>,
    /// Compression scheme name for block-compressed formats (e.g. "BC", "ETC2").
    pub compressed: Option<&'static str>,
    /// Image aspects applicable to this format.
    pub aspects: vk::ImageAspectFlags,
    /// Number of valid entries in `components`.
    pub num_components: u8,
    /// Component descriptions, padded to 4 entries.
    pub components: [ComponentInfo; 4],
    /// Number of valid entries in `planes`. 0 for single-plane formats.
    pub num_planes: u8,
    /// Plane descriptions for multi-planar YCbCr formats, padded to 3 entries.
    pub planes: [PlaneInfo; 3],
    /// SPIR-V image format name, if any.
    pub spirv_image_format: Option<&'static str>,
    /// Format class (e.g. "32-bit", "BC1_RGB", "D16S8").
    pub class: &'static str,
}

